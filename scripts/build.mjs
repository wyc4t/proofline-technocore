// Bundles src/ (ES modules, unit-tested) into ONE classic script, dist/app.js, so the static site
// works from any host and when app.html is opened directly from disk (browsers block module scripts on file://).
import fs from 'node:fs';
import {exampleOutputs} from './examples.mjs';
const root = new URL('../', import.meta.url);
const read = (p) => fs.readFileSync(new URL(p, root), 'utf8');
const order = ['src/lib/archive-epoch.js', 'src/lib/presentation.js', 'src/lib/signature.js', 'src/lib/snapshot.js', 'src/lib/protocol.js', 'src/lib/examples.js', 'src/lib/lookup.js', 'src/lib/population.js', 'src/lib/cases.js', 'src/lib/selection.js', 'src/lib/evidence.js', 'src/lib/store.js', 'src/lib/canvas.js', 'src/app.js'];
const strip = (src) => src.replace(/^import .*;\s*$/gm, '').replace(/^export (async function|function|const|let) /gm, '$1 ');
const body = order.map((f) => `/* ${f} */\n${strip(read(f))}`).join('\n');
if (/^\s*(import|export)\b/m.test(body)) throw new Error('unhandled import/export left in bundle');
const out = `/* GENERATED by scripts/build.mjs from src/. Do not edit; run \`npm run build\`. */\n(() => {\n${body}\n})();\n`;
for (const [file, content] of exampleOutputs(root)) {
  if (process.argv.includes('--check')) { if (read(file) !== content) throw new Error(`${file} is stale`); }
  else { fs.mkdirSync(new URL('dist/examples-data/',root), {recursive:true}); fs.writeFileSync(new URL(file,root), content); }
}
const presentation = read('src/lib/presentation.js');
if (process.argv.includes('--check') && read('dist/presentation.js') !== presentation) throw new Error('dist/presentation.js is stale');
if (!process.argv.includes('--check')) fs.writeFileSync(new URL('dist/presentation.js', root), presentation);
if (process.argv.includes('--check')) { if (read('dist/app.js') !== out) { console.error('dist/app.js is stale: run npm run build'); process.exit(1); } console.log('dist/app.js is up to date'); }
else { fs.writeFileSync(new URL('dist/app.js', root), out); console.log(`dist/app.js written (${out.length} bytes)`); }
